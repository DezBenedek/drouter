const englishByHungarian = Object.fromEntries(
  Object.entries(dictionaries.hu).map(([key, value]) => [value, key]),
);
export const language = () => preferred;
export function t(key, values = {}) {
  const detail = key.match(/^[a-z_]+: (.+)$/);
  const translatedKey = detail && dictionaries.en[detail[1]] ? detail[1] : key;
  let text =
    dictionaries[preferred][translatedKey] ||
    dictionaries.en[translatedKey] ||
    key;
  for (const [name, value] of Object.entries(values))
    text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
export function setLanguage(value) {
  preferred = value === "hu" ? "hu" : "en";
  try {
    localStorage.setItem("drouter-language", preferred);
  } catch {}
  document.documentElement.lang = preferred;
  localize(document.body);
  document
    .querySelectorAll("[data-language]")
    .forEach((el) => (el.value = preferred));
  document.dispatchEvent(new Event("drouter-language"));
}
export const languageControl = () =>
  `<select data-language aria-label="${t("Language")}"><option value="en" ${preferred === "en" ? "selected" : ""}>English</option><option value="hu" ${preferred === "hu" ? "selected" : ""}>Magyar</option></select>`;
const originals = new WeakMap();
function translated(text) {
  const lead = text.match(/^\s*/)[0],
    tail = text.match(/\s*$/)[0],
    key = text.trim();
  if (!key) return text;
  if (dictionaries.hu[key]) return lead + t(key) + tail;
  if (englishByHungarian[key]) return lead + t(englishByHungarian[key]) + tail;
  const detail = key.match(/^[a-z_]+: (.+)$/);
  if (detail && dictionaries.hu[detail[1]]) return lead + t(detail[1]) + tail;
  for (const [pattern, replacement] of patterns) {
    const match = key.match(pattern);
    if (match)
      return (
        lead +
        (preferred === "hu" ? replacement(...match.slice(1)) : key) +
        tail
      );
  }
  return text;
}
export function localize(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest("script,style,[data-user-content]"))
      continue;
    const previous = originals.get(node);
    const source =
      previous && node.data === previous.translated
        ? previous.source
        : node.data;
    const result = translated(source);
    if (node.data !== result) node.data = result;
    originals.set(node, { source, translated: result });
  }
  for (const el of root.querySelectorAll?.(
    "[placeholder],[aria-label],[title]",
  ) || [])
    for (const attr of ["placeholder", "aria-label", "title"]) {
      if (!el.hasAttribute(attr) || el.closest("[data-user-content]")) continue;
      const key = `data-i18n-${attr}`,
        old = el.getAttribute(key),
        current = el.getAttribute(attr);
      const source = old && current === translated(old) ? old : current;
      el.setAttribute(key, source);
      const result = translated(source);
      if (current !== result) el.setAttribute(attr, result);
    }
}
let installed = false;
export function installLocalization() {
  if (installed) return;
  installed = true;
  document.documentElement.lang = preferred;
  let scheduled = false;
  const update = () => {
    scheduled = false;
    if (!document.querySelector("[data-language]")) {
      const target = document.querySelector(
        ".auth-brand,.topbar-actions,.simple-screen header",
      );
      if (target) target.insertAdjacentHTML("beforeend", languageControl());
    }
    for (const host of document.querySelectorAll("[data-language-host]")) {
      if (!host.querySelector("[data-language]"))
        host.innerHTML = languageControl();
    }
    localize(document.body);
  };
  new MutationObserver(() => {
    if (!scheduled) {
      scheduled = true;
      queueMicrotask(update);
    }
  }).observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  });
  document.addEventListener("change", (event) => {
    if (event.target.matches("[data-language]"))
      setLanguage(event.target.value);
  });
  update();
}
