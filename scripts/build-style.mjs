import { fileURLToPath } from "node:url";
import sass from "../cloud/node_modules/sass/sass.node.js";
import { readFile, writeFile } from "node:fs/promises";
import { transform } from "../cloud/node_modules/esbuild/lib/main.js";
process.chdir(fileURLToPath(new URL("..", import.meta.url)));
const foundation = sass.compile("scripts/pico.scss", {
  style: "compressed",
}).css;
const custom = await readFile("scripts/design.css", "utf8");
const { code } = await transform(`@layer pico { ${foundation} }\n${custom}`, {
  loader: "css",
  minify: true,
  legalComments: "inline",
});
await writeFile(
  "firmware/web/shared/style.css",
  `/* Pico CSS 2.1.1 · MIT · picocss.com | DRouter design system. Generated by scripts/build-style.mjs. */\n${code}`,
);
