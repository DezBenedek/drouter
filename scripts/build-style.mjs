import { fileURLToPath } from "node:url";
import { readFile, writeFile } from "node:fs/promises";
import { transform } from "../cloud/node_modules/esbuild/lib/main.js";
process.chdir(fileURLToPath(new URL("..", import.meta.url)));
// Bundle Oat locally so the controller works without internet or a CDN.
const foundation = await readFile(
  "cloud/node_modules/@knadh/oat/oat.min.css",
  "utf8",
);
const custom = await readFile("scripts/design.css", "utf8");
const { code } = await transform(`@layer oat { ${foundation} }\n${custom}`, {
  loader: "css",
  minify: true,
  legalComments: "inline",
});
await writeFile(
  "firmware/web/shared/style.css",
  `/* Oat UI 1.0.0 · MIT · oat.ink | DRouter. Generated by scripts/build-style.mjs. */\n${code}`,
);
